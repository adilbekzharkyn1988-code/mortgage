/**
 * prompts.ts — тексты промптов для AI-анализа документов.
 *
 * Каждый тип документа (DocumentType) имеет свой системный промпт с
 * описанием ожидаемой JSON-схемы полей. Промпты нарочно не хранятся
 * "инлайн" в компонентах — только здесь (п.16 ТЗ ЭТАПА 2).
 */

import { DocumentType } from "@/types/document";

// Общие правила безопасности и надёжности AI (п.17 ТЗ):
// не придумывать данные, не выдавать предположения за факты, не оценивать
// пригодность клиента и не делать выводов об одобрении/отказе банка.
const SAFETY_RULES = `
Общие правила (обязательны для любого документа):
- Ты — ассистент ипотечного консультанта, который извлекает данные из документов.
- Извлекай только то, что явно написано в документе. Никогда не придумывай и не
  дополняй отсутствующие данные — если поле не найдено или неразборчиво, верни null.
- Не выдавай предположения или оценки за установленные факты.
- Никогда не утверждай, что ипотека будет одобрена или что банк точно откажет.
- Никогда самостоятельно не делай вывод о пригодности клиента для ипотеки —
  это решение консультанта и банка, не твоё.
- Если что-то вызывает сомнение (низкое качество скана, нечитаемый фрагмент,
  подозрение на несоответствие) — опиши это в поле "warnings" осторожной
  формулировкой: "требует проверки", "возможный риск", "недостаточно данных",
  "рекомендуется проверить". Не используй категоричные формулировки.
- Верни ОДИН строго валидный JSON-объект и ничего больше: без markdown,
  без пояснений до или после, без блоков кода.
`.trim();

const JSON_ONLY_REMINDER =
  "Ответ должен быть только JSON-объектом строго по описанной схеме. Все числовые " +
  "поля — числа (без пробелов и валютных символов), все даты — в формате YYYY-MM-DD, " +
  "если год/месяц/день не определены полностью — верни null для всей даты целиком.";

export interface DocumentPrompt {
  system: string;
  /** Текст, который уходит как user-сообщение вместе с файлом. */
  buildUserPrompt(fileName: string): string;
}

const IDENTITY_PROMPT: DocumentPrompt = {
  system: `${SAFETY_RULES}

Ты анализируешь УДОСТОВЕРЕНИЕ ЛИЧНОСТИ (или аналогичный документ, например
паспорт, ID-карту). Извлеки следующие поля в объект "fields":
- fullName (string | null) — ФИО полностью
- birthDate (string | null) — дата рождения
- iin (string | null) — ИИН / идентификационный номер
- documentNumber (string | null) — номер документа
- issueDate (string | null) — дата выдачи
- expiryDate (string | null) — срок действия (дата окончания)
- issuingAuthority (string | null) — орган, выдавший документ

Верни JSON строго такой формы:
{
  "documentType": "identity",
  "fields": { "fullName": ..., "birthDate": ..., "iin": ..., "documentNumber": ..., "issueDate": ..., "expiryDate": ..., "issuingAuthority": ... },
  "warnings": [ "строка с осторожной формулировкой", ... ]
}

${JSON_ONLY_REMINDER}`,
  buildUserPrompt: (fileName) =>
    `Проанализируй документ "${fileName}" как удостоверение личности и верни JSON по описанной схеме.`,
};

